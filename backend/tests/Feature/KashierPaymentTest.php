    /**
     * Build valid Kashier callback/webhook query params with a correct HMAC signature.
     * Mirrors the algorithm in KashierService::validateSignature().
     */
    private function buildKashierParams(string $orderRef, string $paymentStatus, string $transactionId = 'TXN-001'): array
    {
        $params = [
            'merchantOrderId' => $orderRef,
            'paymentStatus'   => $paymentStatus,
            'transactionId'   => $transactionId,
            'orderId'         => 'KSH-999',
            'currency'        => 'EGP',
            'amount'          => number_format(self::PACKAGE_PRICE, 2, '.', ''),
            'cardBrand'       => 'VISA',
        ];

        // Build query string the same way KashierService does (exclude 'signature' and 'mode')
        $queryString = '';
        foreach ($params as $key => $value) {
            $queryString .= "&{$key}={$value}";
        }
        $queryString = ltrim($queryString, '&');

        $params['signature'] = hash_hmac('sha256', $queryString, self::TEST_API_KEY, false);

        return $params;
    }

