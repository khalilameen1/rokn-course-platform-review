   public function test_authenticated_user_can_initiate_payment_for_a_package(): void
    {
        $response = $this->actingAs($this->user, 'api')
            ->postJson('/api/v1/payment/initiate', [
                'package_id' => $this->package->id,
            ]);

        $response->assertStatus(200)
            ->assertJsonPath('success', true)
            ->assertJsonPath('status', 200)
            ->assertJsonPath('data.order_ref', $response->json('order_ref'))
            ->assertJsonStructure([
                'status',
                'success',
                'data',
                'message',
                'payment_url',
                'order_ref',
                'amount',
                'package' => ['id', 'name_ar', 'name_en', 'coins'],
            ]);

        // order_ref must start with 'PKG-'
        $this->assertStringStartsWith('PKG-', $response->json('order_ref'));

        // payment_url must be a valid Kashier checkout URL
        $this->assertStringContainsString('checkout.kashier.io', $response->json('payment_url'));
        $this->assertStringContainsString('MID-', $response->json('payment_url'));

        // A pending order must exist in the DB
        $this->assertDatabaseHas('orders', [
            'user_id'        => $this->user->id,
            'package_id'     => $this->package->id,
            'payment_method' => 'kashier',
            'status'         => 'pending',
            'financial_status' => Order::FINANCIAL_PENDING,
        ]);
    }

