export default function TermsOfUse() {
  const [managedBody, setManagedBody] = useState('');
  useEffect(() => {
    let active = true;
    void getManagedPublicContent('terms')
      .then(body => active && setManagedBody(body))
      .catch(() => undefined);
    return () => {
      active = false;
    };
  }, []);
  const visibleSections = useMemo(
    () => (managedBody ? [['شروط الاستخدام', managedBody]] : sections),
    [managedBody],
  );
  return (
    <Container noPadding>
      <Content noPadding>
        <ResponsiveFrame>
          <HeaderWithBack title="شروط الاستخدام" />
          <Text style={styles.intro}>
            باستخدام ركن أو إنشاء حساب أو إتمام معاملة، فأنت توافق على هذه
            الشروط. كتبناها بلغة مباشرة حتى تعرف حقك ومسؤوليتك قبل أن تبدأ.
          </Text>
          <Text style={styles.updated}>آخر تحديث: ٣١ أغسطس ٢٠٢٦</Text>
          <View style={styles.list}>
            {visibleSections.map(([title, body]) => (
              <PremiumCard key={title} style={styles.card}>
                <Text style={styles.title}>{title}</Text>
                <Text style={styles.body}>{body}</Text>
              </PremiumCard>
            ))}
          </View>
        </ResponsiveFrame>
      </Content>
    </Container>
  );
}

const styles = StyleSheet.create({
  intro: {
    ...Type.body,
    ...textDirection,
    color: Palette.textMuted,
    marginTop: Spacing.lg,
  },
  updated: {
    ...Type.caption,
    ...textDirection,
    color: Palette.textFaint,
    marginTop: Spacing.sm,
    marginBottom: Spacing.lg,
  },
  list: {gap: Spacing.sm, paddingBottom: Spacing.xl},
  card: {padding: Spacing.lg},
  title: {...Type.section, ...textDirection, color: Palette.text},
  body: {...Type.body, ...textDirection, color: Palette.textMuted, marginTop: Spacing.xs},
});
